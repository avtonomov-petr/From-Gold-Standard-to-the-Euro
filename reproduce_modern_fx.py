import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

NL = chr(10)

# 1. Загрузка исторических курсов Clio Infra (1870-2013, T=144)
xl_fx = pd.ExcelFile('ExchangeRatestoUKPound_Compact.xlsx')
df_long = xl_fx.parse('Data Long Format')
df_long['year'] = pd.to_numeric(df_long['year'], errors='coerce')
df_long['value'] = pd.to_numeric(df_long['value'], errors='coerce')

sub_all = df_long[(df_long['year'].between(1870, 2013)) & (df_long['value'] > 0)].dropna(subset=['value'])
piv_all = sub_all.pivot_table(index='year', columns='country.name', values='value').reindex(range(1870, 2014))

COUNTRIES_21 = [
    'United Kingdom', 'Switzerland', 'Sweden', 'Finland', 'Portugal', 'Italy',
    'France', 'Netherlands', 'Spain', 'Belgium', 'Denmark', 'Austria',
    'Australia', 'New Zealand', 'Canada', 'Japan', 'India',
    'Argentina', 'Brazil', 'Chile', 'Mexico'
]
COUNTRIES_20_GBP = [c for c in COUNTRIES_21 if c != 'United Kingdom']

piv_gbp = piv_all[COUNTRIES_20_GBP].interpolate(method='linear', limit_direction='both')
usd_ser = piv_all['United States'].interpolate(method='linear', limit_direction='both')
piv_usd = piv_all[COUNTRIES_21].interpolate(method='linear', limit_direction='both').div(usd_ser, axis=0)

def safe_zscore(M_arr):
    mean_v = np.mean(M_arr, axis=0)
    std_v = np.std(M_arr, axis=0, ddof=1)
    safe_std = np.where(std_v > 1e-12, std_v, 1.0)
    Z = (M_arr - mean_v) / safe_std
    Z[:, std_v <= 1e-12] = 0.0
    return Z

# 2. Калибровка 4 монетарных режимов и 95% бутстрэп-интервалы (Таблица 1)
dln_usd = np.diff(np.log(piv_usd.to_numpy(dtype=float)), axis=0)
dln_gbp = np.diff(np.log(piv_gbp.to_numpy(dtype=float)), axis=0)
yrs = np.arange(1871, 2014)

regimes_cfg = [
    ("Classical Gold Standard (1871-1913)", 1871, 1913),
    ("Interwar and Depression (1919-1939)", 1919, 1939),
    ("Bretton Woods Peg (1946-1971)", 1946, 1971),
    ("Post-Bretton Woods Float (1973-2013)", 1973, 2013)
]

print("=== TABLE 1: GLOBAL CURRENCY REGIMES CALIBRATION ===")
rng = np.random.default_rng(42)

for r_name, y0, y1 in regimes_cfg:
    m = (yrs >= y0) & (yrs <= y1)
    Xu = dln_usd[m, :]
    Zu = safe_zscore(Xu)
    Mu, Nu = Zu.shape
    Uu, su, Vtu = np.linalg.svd(Zu, full_matrices=False)
    u1u, v1u = np.take(Uu, 0, axis=1), np.take(Vtu, 0, axis=0)
    var1u = (su.item(0)**2) / np.sum(su**2) * 100.0
    pru = (1.0 / np.sum(u1u**4) - 1.0) / (Mu - 1.0)
    prv = (1.0 / np.sum(v1u**4) - 1.0) / (Nu - 1.0)

    sub_m = int(np.floor(Mu * 0.8))
    bu, bv = [], []
    for _ in range(300):
        idx = np.sort(rng.choice(Mu, size=sub_m, replace=False))
        Ub, _, Vtb = np.linalg.svd(safe_zscore(Xu[idx, :]), full_matrices=False)
        u1b, v1b = np.take(Ub, 0, axis=1), np.take(Vtb, 0, axis=0)
        bu.append((1.0 / np.sum(u1b**4) - 1.0) / (sub_m - 1.0))
        bv.append((1.0 / np.sum(v1b**4) - 1.0) / (Nu - 1.0))

    Xg = dln_gbp[m, :]
    Zg = safe_zscore(Xg)
    Ug, _, _ = np.linalg.svd(Zg, full_matrices=False)
    u1g = np.take(Ug, 0, axis=1)
    prug = (1.0 / np.sum(u1g**4) - 1.0) / (len(u1g) - 1.0)
    print(f"{r_name:<38} | M={Mu:2d} | Var1={var1u:4.1f}% | PR(u1)={pru:.3f} [{np.percentile(bu, 2.5):.3f}, {np.percentile(bu, 97.5):.3f}] | PR(v1)={prv:.3f} [{np.percentile(bv, 2.5):.3f}, {np.percentile(bv, 97.5):.3f}] | GBP_PR(u1)={prug:.3f}")

